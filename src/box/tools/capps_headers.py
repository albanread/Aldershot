"""capps_headers.py -- the staged headers as a client includes them (packages T4b and Q1).

make capps stages headers for clients: OUT/inc (C:, RISCOSLIB:, tbox:, OS:)
and the applications' and the Toolbox's own h/ files under OUT/src.  The
source pass (tools/capps_pass.py) edits only what a unit it parses reaches,
and the built units (the library, rlib, the Toolbox) reach a fraction of
them: without more, a client of oslib/wimp.h or of Draw's h/ files would get
clang's layouts, not Norcroft's.  So every staged client header belongs to a
group:

  a group is one translation unit, OUT/hdrunits/<name>.c, that includes the
  group's headers in order, each after the headers its users include before
  it, with the group's include path.  The pass parses each group as a unit
  (capps.py stage adds them to its units; rules.mk builds none of them), and
  Q1's layout probes (tests/capps/layout) measure the records defined in the
  group's directories, from the same unit, on the farm and for x32.

A header that parses on its own needs nothing before it.  One that does not
gets the #include lines that come before it in a staged file that includes
it (a "user"), or failing that in a user of a twin (the same file staged in
another place: rlib's h/ is src/Lib/RISC_OSLib/rlib and inc/RISCOSLIB, and
ToolboxLib's is inc/tbox and inc/C/tboxlibs), the first whose lines make it
parse, or failing that one of a few common contexts (kernel.h; OSLib's
os.h).  A header that parses in no context is excluded, with clang's error
as the reason; make capps prints the list, and Q1's compare fails unless
its known.txt lists each with the reason.  A header that parses but breaks
its group's unit (a clash) gets a group of its own ("<group>.<n>").

The libraries exported to C: are staged whole, but a client on RISC OS sees
only what each exports (its Makefile's HDRS): their groups are those, and
what those include.

The groups are worked out when the staged tree changes and kept in
OUT/hdrgroups.json, keyed by the staged files, the compiler and flags, and
this file.  Paths in it are OUT-relative.
"""
import collections
import concurrent.futures
import functools
import hashlib
import json
import os
import re
import subprocess

# The applications whose h/ files are staged for clients (proposal revision 3,
# phase 3): OUT/src/Apps/<name>, from Sources/<where>.  Their Makefiles put
# RISCOSLIB: on the path after their own directory (Help reaches ToolboxLib
# as C:'s "tboxlibs/...").
APPS = collections.OrderedDict([
    ("Draw", "Apps/Draw"),
    ("Edit", "Apps/EditApp"),
    ("Paint", "Apps/Paint"),
    ("FilerAct", "Desktop/FilerAct"),
    ("Help", "Apps/Help2"),
])

C_PATH = ["inc/C", "inc/RISCOSLIB"]           # C: as capps.py's c_path has it
TBOX_PATH = ["inc/tbox"] + C_PATH              # -Itbox:,C:
OS_PATH = ["inc/OS"] + C_PATH                  # -IOS:,C:

# Staged under h/ but not C: each with why.
NOT_HEADERS = {
    "inc/RISCOSLIB/README.h": "rlib's h.README is a text file, not C",
}

# Tried, in order, for a header that parses neither alone nor after any
# user's lines (none includes it): the kernel's types, then OSLib's
COMMON_PRELUDES = [["kernel.h"], ["kernel.h", "swis.h"], ["oslib/types.h", "oslib/os.h"],
                   ["kernel.h", "os.h", "wimp.h"]]

_INCLUDE = re.compile(r'^[ \t]*#[ \t]*include[ \t]*([<"])([^>"]+)[>"]', re.M)


class Group:
    """name; path: the include path (OUT-relative directories, in order);
    headers: the group's own headers; lines: the unit's #include names, in
    order; dirs: where the records Q1 measures are defined ("d/*" the files
    in d, "d/**" and those under it)."""

    def __init__(self, name, path, headers, lines=None, dirs=None):
        self.name, self.path, self.headers = name, list(path), list(headers)
        self.lines, self.dirs = list(lines or []), list(dirs or [])

    def to_json(self):
        return {"name": self.name, "path": self.path, "headers": self.headers, "lines": self.lines,
                "dirs": self.dirs}

    @staticmethod
    def from_json(d):
        return Group(d["name"], d["path"], d["headers"], d["lines"], d["dirs"])

    def owns(self, rel):
        """Is an OUT-relative file in the group's directories?"""
        for d in self.dirs:
            base, how = d.rsplit("/", 1)
            if how == "**" and rel.startswith(base + "/"):
                return True
            if how == "*" and os.path.dirname(rel) == base:
                return True
        return False

    def unit_text(self):
        return ("/* %s -- generated by tools/capps_headers.py: the staged headers of group\n"
                " * %s, each after what its users include before it (a unit of the source\n"
                " * pass; Q1's layout probe of the group is this and its tables). */\n"
                % (self.name, self.name) + "".join('#include "%s"\n' % n for n in self.lines))


def _hfiles(out, d, recursive):
    base = os.path.join(out, d)
    res = []
    if not os.path.isdir(base):
        return res
    if recursive:
        for dp, dn, fn in os.walk(base):
            dn.sort()
            res += [os.path.relpath(os.path.join(dp, f), out) for f in sorted(fn) if f.endswith(".h")]
    else:
        res = [os.path.join(d, f) for f in sorted(os.listdir(base))
               if f.endswith(".h") and os.path.isfile(os.path.join(base, f))]
    return res


def _dedup(xs):
    res = []
    for x in xs:
        if x not in res:
            res.append(x)
    return res


def specs(out, libs, toolbox):
    """The groups before discovery: [(name, include path, own headers, dirs)].
    out: the tree to look in (OUT/pre).  libs: {library exported to C:
    (capps.py's C_EXPORTS): (its include path, its exported headers, or None
    for all)}.  toolbox: {src/Toolbox/X: the include path of X's units}."""
    res = []
    top = [h for h in _hfiles(out, "inc/C", False) if h != "inc/C/ToolAction.h"]
    res.append(("clib", C_PATH, top, ["inc/C/*"]))
    res.append(("global", C_PATH, _hfiles(out, "inc/C/Global", True) + _hfiles(out, "inc/C/Interface", True),
                ["inc/C/Global/**", "inc/C/Interface/**"]))
    for lib in sorted(libs, key=str.lower):
        path, hdrs = libs[lib]
        d = "inc/C/" + lib
        allh = _hfiles(out, d, True)
        own = allh if hdrs is None else [h for h in hdrs if h in allh]
        res.append((lib.lower(), _dedup(path + C_PATH + [d]), own, [d + "/**"]))
    res.append(("tboxlibs", C_PATH, _hfiles(out, "inc/C/tboxlibs", True), ["inc/C/tboxlibs/**"]))
    res.append(("rlib", C_PATH, _hfiles(out, "inc/RISCOSLIB", False), ["inc/RISCOSLIB/*"]))
    res.append(("tbox", TBOX_PATH, _hfiles(out, "inc/tbox", False), ["inc/tbox/*"]))
    if os.path.isfile(os.path.join(out, "inc/C/ToolAction.h")):
        # DefMod's header for ToolAction, which its Makefile exports to C:
        res.append(("toolaction", _dedup(toolbox.get("src/Toolbox/ToolAction", []) + OS_PATH + TBOX_PATH),
                    ["inc/C/ToolAction.h"], []))
    res.append(("oslib", OS_PATH, _hfiles(out, "inc/OS/oslib", False), ["inc/OS/oslib/*"]))
    res.append(("os", OS_PATH, _hfiles(out, "inc/OS", False), ["inc/OS/*"]))
    for name in APPS:
        d = "src/Apps/" + name
        res.append((name.lower(), [d] + C_PATH, _hfiles(out, d, True), [d + "/**"]))
    tb = os.path.join(out, "src", "Toolbox")
    if os.path.isdir(tb):
        for m in sorted(os.listdir(tb)):
            d = "src/Toolbox/" + m
            hs = _hfiles(out, d, True)
            if not hs:
                continue
            # every unit's path in the component, then each header's directory
            path = []
            for k, p in sorted(toolbox.items()):
                if k == d or k.startswith(d + "/"):
                    path += p
            path = _dedup((path or [d] + TBOX_PATH) + sorted({os.path.dirname(h) for h in hs}))
            res.append(("toolbox-" + m.lower(), path, hs, [d + "/**"]))
    return [(n, p, [h for h in hs if h not in NOT_HEADERS], ds) for n, p, hs, ds in res if hs]


