# discovery

def _includes(path):
    try:
        with open(path, "rb") as f:
            t = f.read().decode("latin-1")
    except OSError:
        return []
    return [m.group(2).strip() for m in _INCLUDE.finditer(t)]


@functools.lru_cache(maxsize=None)
def _isfile(p):
    return os.path.isfile(p)


def _resolve(name, where, path, out):
    """An include name -> OUT-relative file, searched from the including
    file's directory (where, OUT-relative) and then the path."""
    for d in ([where] if where is not None else []) + list(path):
        p = os.path.normpath(os.path.join(d, name))
        if _isfile(os.path.join(out, p)):
            return p
    return None


def _canonical(rel, path):
    """The name a unit with this include path includes an OUT-relative file by."""
    for d in path:
        if rel.startswith(d + "/"):
            return rel[len(d) + 1:]
    return None


class _Clang:
    def __init__(self, cc, cflags, out, tmp):
        self.cc, self.cflags, self.out, self.tmp = cc, cflags, out, tmp
        os.makedirs(tmp, exist_ok=True)

    def parses(self, path, lines, tag):
        """None if the unit parses, else clang's first error."""
        src = os.path.join(self.tmp, tag + ".c")
        with open(src, "w") as f:
            f.write("".join('#include "%s"\n' % n for n in lines))
        argv = self.cc + self.cflags + ["-I" + os.path.join(self.out, d) for d in path] + \
            ["-w", "-fsyntax-only", src]
        r = subprocess.run(argv, capture_output=True, text=True, errors="replace")
        if r.returncode == 0:
            return None
        errs = [l for l in r.stderr.split("\n") if "error:" in l]
        e = errs[0] if errs else r.stderr.strip().split("\n")[-1]
        return e.replace(self.out + "/", "").replace(self.tmp + "/", "")


def discover(out, group_specs, cc, cflags, users, jobs, tmp):
    """Each header's prelude, then the groups' units.  users: every staged
    file (OUT-relative) whose #include lines count.
    -> ([Group], {header: reason excluded})"""
    clang = _Clang(cc, cflags, out, tmp)
    inc_of = {u: _includes(os.path.join(out, u)) for u in users}
    roots = _dedup([d for _, p, _, _ in group_specs for d in p])
    digest = {}
    for u in users:
        with open(os.path.join(out, u), "rb") as f:
            digest[u] = hashlib.sha256(f.read()).hexdigest()
    by_digest = collections.defaultdict(list)
    for u, d in digest.items():
        by_digest[d].append(u)

    def preludes(h, path):
        """Candidate preludes for h: (rank, user, [include names in path])"""
        cands = []
        twins = [t for t in by_digest.get(digest.get(h), []) if t != h and os.path.basename(t) == os.path.basename(h)]
        for target, rank in [(h, 0)] + [(t, 2) for t in sorted(twins)]:
            tdir, hdir = os.path.dirname(target), os.path.dirname(h)
            # a twin's users are resolved as its own context has them
            upath = path if target == h else _dedup([tdir] + path + roots)
            for u in users:
                names = inc_of[u]
                where = os.path.dirname(u)
                for i, n in enumerate(names):
                    if _resolve(n, where, upath, out) != target:
                        continue
                    pre = []
                    for m in names[:i]:
                        r = _resolve(m, where, upath, out)
                        if r and target != h and r.startswith(tdir + "/"):
                            moved = hdir + r[len(tdir):]
                            r = moved if os.path.isfile(os.path.join(out, moved)) else None
                        c = _canonical(r, path) if r else None
                        if c is None:
                            pre = None
                            break
                        if c not in pre:
                            pre.append(c)
                    if pre is not None:
                        near = os.path.commonpath([tdir, where]) == tdir
                        cands.append((rank + (0 if near else 1), u, pre))
                    break
        return sorted(cands)

    def prelude_for(args):
        gname, path, h, k = args
        own = _canonical(h, path)
        if own is None:
            return h, None, "not under the group's include path"
        err = clang.parses(path, [own], "%s-%d" % (gname, k))
        if err is None:
            return h, [own], None
        seen, tried = set(), []
        for _, u, pre in preludes(h, path):
            key = tuple(pre)
            if key in seen or not pre:
                continue
            seen.add(key)
            e2 = clang.parses(path, pre + [own], "%s-%d" % (gname, k))
            if e2 is None:
                return h, pre + [own], None
            tried.append("after %s's includes: %s" % (u, e2))
            if len(seen) >= 12:
                break
        # no user's lines: the contexts RISC OS C most often assumes
        for pre in COMMON_PRELUDES:
            pre = [n for n in pre if _resolve(n, None, path, out)]
            if pre and tuple(pre) not in seen:
                seen.add(tuple(pre))
                if clang.parses(path, pre + [own], "%s-%d" % (gname, k)) is None:
                    return h, pre + [own], None
        return h, None, "; ".join([err] + tried[:2])

    work = [(g, p, h, i) for gi, (g, p, hs, _) in enumerate(group_specs) for i, h in enumerate(hs)]
    with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as ex:
        found = {h: (lines, err) for h, lines, err in ex.map(prelude_for, work)}
    excluded = {}

    def build(name, path, hs, dirs):
        lines, own = [], []
        for h in hs:
            ls, err = found[h]
            if ls is None:
                excluded[h] = err
                continue
            for n in ls:
                if n not in lines:
                    lines.append(n)
            own.append(h)
        return Group(name, path, own, lines, dirs)

    def split(g):
        """A group whose unit does not parse: the longest run of its headers
        that parses stays (found by bisection); the header that ends the run
        goes to a group of its own; the rest are tried after the run."""
        def ok(hs):
            return clang.parses(g.path, build(g.name, g.path, hs, g.dirs).lines, g.name + "-split") is None
        base, alone, rest = [], [], list(g.headers)
        while rest:
            if ok(base + rest):
                base += rest
                break
            lo, hi = 0, len(rest)          # base + rest[:lo] parses, base + rest[:hi] does not
            while hi - lo > 1:
                mid = (lo + hi) // 2
                if ok(base + rest[:mid]):
                    lo = mid
                else:
                    hi = mid
            base += rest[:lo]
            alone.append(rest[lo])
            rest = rest[lo + 1:]
        res = [build(g.name, g.path, base, g.dirs)] if base else []
        for i, h in enumerate(alone):
            res.append(build("%s.%d" % (g.name, i + 1), g.path, [h], [h.rsplit("/", 1)[0] + "/*"]))
        return res

    todo = [build(n, p, hs, ds) for n, p, hs, ds in group_specs]
    with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as ex:
        ok = list(ex.map(lambda g: g.headers and clang.parses(g.path, g.lines, g.name + "-all") is None, todo))
    groups = []
    for g, good in zip(todo, ok):
        if g.headers:
            groups += [g] if good else split(g)
    return groups, excluded


def groups(out, pre, cc, cflags, libs, toolbox, jobs, staged):
    """The groups for the tree staged in pre (OUT/pre), cached in
    OUT/hdrgroups.json; each group's unit is written to OUT/hdrunits/.
    staged: every staged path (absolute), for the key and as the users.
    -> ([Group], {header: reason excluded})"""
    gs = specs(pre, libs, toolbox)
    h = hashlib.sha256()
    for x in (cc, cflags, gs, sorted(NOT_HEADERS.items())):
        h.update(repr(x).encode() + b"\0")
    for p in [os.path.abspath(__file__)] + sorted(staged):
        h.update(p.encode() + b"\0")
        with open(p, "rb") as f:
            h.update(hashlib.sha256(f.read()).digest())
    key = h.hexdigest()
    cache = os.path.join(out, "hdrgroups.json")
    res = None
    try:
        with open(cache) as f:
            c = json.load(f)
        if c.get("key") == key:
            res = [Group.from_json(g) for g in c["groups"]], c["excluded"]
    except (OSError, ValueError, KeyError):
        pass
    if res is None:
        users = sorted(os.path.relpath(p, pre) for p in staged
                       if p.startswith(pre + os.sep) and p.endswith((".c", ".h")))
        res = discover(pre, gs, cc, cflags, users, jobs, os.path.join(out, "tmp", "hdrgroups"))
        with open(cache + ".tmp", "w") as f:
            json.dump({"key": key, "groups": [g.to_json() for g in res[0]], "excluded": res[1]},
                      f, indent=1, sort_keys=True)
        os.replace(cache + ".tmp", cache)
    write_units(out, res[0])
    return res


def load(out):
    """The groups make capps worked out: ([Group], {header: reason})."""
    with open(os.path.join(out, "hdrgroups.json")) as f:
        c = json.load(f)
    return [Group.from_json(g) for g in c["groups"]], c["excluded"]


def unit_path(out, g):
    return os.path.join(out, "hdrunits", g.name + ".c")


def write_units(out, gs):
    d = os.path.join(out, "hdrunits")
    os.makedirs(d, exist_ok=True)
    want = set()
    for g in gs:
        p = unit_path(out, g)
        want.add(os.path.basename(p))
        t = g.unit_text()
        try:
            with open(p) as f:
                if f.read() == t:
                    continue
        except OSError:
            pass
        with open(p, "w") as f:
            f.write(t)
    for f in os.listdir(d):
        if f not in want:
            os.remove(os.path.join(d, f))
